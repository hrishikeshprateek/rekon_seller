package com.reckon.reckonorders.NewDesign.NewModals;

public class ThemeColorModel {

    private String statusBarColor;
    private String headerTextColor;
    private String thirdHeaderTextColor;
    private String secondHeaderTextColor;
    private boolean lightIcon;
    private String buttonColor;




    public String getThirdHeaderTextColor() {
        return thirdHeaderTextColor;
    }

    public void setThirdHeaderTextColor(String thirdHeaderTextColor) {
        this.thirdHeaderTextColor = thirdHeaderTextColor;
    }

    public String getStatusBarColor() {
        return statusBarColor;
    }

    public void setStatusBarColor(String statusBarColor) {
        this.statusBarColor = statusBarColor;
    }

    public String getHeaderTextColor() {
        return headerTextColor;
    }

    public void setHeaderTextColor(String headerTextColor) {
        this.headerTextColor = headerTextColor;
    }

    public boolean isLightIcon() {
        return lightIcon;
    }

    public void setLightIcon(boolean lightIcon) {
        this.lightIcon = lightIcon;
    }

    public String getButtonColor() {
        return buttonColor;
    }

    public void setButtonColor(String buttonColor) {
        this.buttonColor = buttonColor;
    }
    public String getSecondHeaderTextColor() {
        return secondHeaderTextColor;
    }

    public void setSecondHeaderTextColor(String secondHeaderTextColor) {
        this.secondHeaderTextColor = secondHeaderTextColor;
    }


}